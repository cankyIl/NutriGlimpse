from pathlib import Path
import json,sys
r=Path(__file__).resolve().parents[1]
library=json.loads((r/'data/guidance/library.json').read_text())
tables=json.loads((r/'data/guidance/serving-tables.json').read_text())['tables']
assert library['personalizedRecommendationsEnabled'] is False
assert all(e['automaticPersonalization'] is False and e['productRecommendationEnabled'] is False and e['reviewedBy'] is None for e in library['entries'])
sources=[{k:s[k] for k in ['id','url','title','sourceVersion','publisher','attribution']} for s in library['sources']]
payload={'version':library['libraryVersion'],'checkedOn':'2026-10-14','personalizedRecommendationsEnabled':False,'sources':sources,'entries':library['entries'],'tables':tables}
content='// Generated by ops/export-guidance-library.py from the checked source archive. Do not edit.\nexport const savedGuidance = '+json.dumps(payload,ensure_ascii=False,indent=1)+';\n'
target=r/'packages/core/src/guidanceLibrary.generated.ts'
if '--check' in sys.argv:
 assert target.read_text()==content,'Run ops/export-guidance-library.py to synchronize the app reference library.'
else: target.write_text(content)
print('Guidance projection verified: %d entries, %d tables'%(len(payload['entries']),len(tables)))
