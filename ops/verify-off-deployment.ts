import {projectRoot} from '../apps/service/src/projectPaths.ts';
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {foodSchema} from '../packages/core/src/publicFood.ts';
import {normalizeBarcode} from '../packages/core/src/barcode.ts';
const root=projectRoot,base='https://grocery.serveforwad.com';
const key=JSON.parse(readFileSync(root+'/.tools/beta/tester-invitations.json','utf8')).testers[0].key;
const headers={Authorization:'Bearer '+key};
const initial=await(await fetch(base+'/v1/catalog/export')).json();assert.equal(initial.license,'ODbL-1.0');initial.foods.forEach((f:unknown)=>foodSchema.parse(f));
assert.ok(!JSON.stringify(initial).includes(key));
assert.equal((await fetch(base+'/v1/catalog/search/hummus')).status,401);
assert.equal((await fetch(base+'/v1/catalog/export',{method:'HEAD'})).status,200);
assert.equal((await fetch(base+'/data-sources')).status,200);
const sample=initial.foods.find((f:{provider:string})=>f.provider==='off');assert.ok(sample);
const lookup=await(await fetch(base+'/v1/catalog/foods/off/'+sample.id,{headers})).json();assert.equal(lookup.food.provider,'off');foodSchema.parse((({stale,...f})=>f)(lookup.food));
const code='016000275263';assert.ok(normalizeBarcode(code));
const wasCached=initial.foods.some((f:{barcode:string})=>f.barcode===normalizeBarcode(code));
const scan=await(await fetch(base+'/v1/catalog/barcodes/'+code,{headers})).json();assert.equal(scan.synthetic,false);scan.foods.forEach(({stale,...f}:{stale:boolean})=>foodSchema.parse(f));
const exported=await(await fetch(base+'/v1/catalog/export')).json();
const health=await(await fetch(base+'/health',{headers})).json();
const portfolio=await fetch('https://portfolio.serveforwad.com');assert.equal(portfolio.status,200);
const report={checkedAt:new Date().toISOString(),publicDownload:true,publicCredits:true,protectedSearch:true,offSourceLookup:true,newBarcodeWasCached:wasCached,newBarcodeResults:scan.foods.length,records:exported.foods.length,offRecords:exported.foods.filter((f:{provider:string})=>f.provider==='off').length,health,portfolioStatus:portfolio.status};
writeFileSync(root+'/artifacts/remote/off/deployment-check.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));
