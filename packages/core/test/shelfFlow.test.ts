import { test } from 'node:test';
import assert from 'node:assert/strict';
import { ShelfSession } from '../src/shelfSession.ts';
import { shelfFoodKey } from '../src/shelfIdentity.ts';
import { rankShelfFoods } from '../src/shelfRanking.ts';
import type { Profile, ConfirmedPanel } from '../src/types.ts';
import { food, observation } from './shelfTestHelpers.ts';

test('observed package evidence flows through confirmation into local profile reranking without unseen catalog products or persistence', () => {
 const now = Date.parse('2026-10-14T12:00:00Z');
 const session = new ShelfSession({ now: () => new Date(now), processNonce: 'integration-process' });
 const lowFat = food(1, { name: 'Testbrand Orchard Original Cereal', nutrients: { caloriesKcal: 350, saturatedFatG: 1, sodiumMg: 500, fiberG: 6, sugarsG: 4 } });
 const lowSodium = food(2, { name: 'Testbrand Meadow Reduced Sugar Cereal', nutrients: { caloriesKcal: 250, saturatedFatG: 5, sodiumMg: 100, fiberG: 6, sugarsG: 2 } });
 const unseen = food(3, { name: 'Testbrand Unseen Shelf Cereal', nutrients: { caloriesKcal: 200, saturatedFatG: 0, sodiumMg: 0, fiberG: 20, sugarsG: 0 } });
 const catalog = [lowFat, lowSodium, unseen];
 const profile: Profile = { revision: 1, age: 40, pregnancy: 'not-pregnant', primary: 'cardiovascular', conditions: ['cardiovascular'], intent: 'both', restrictions: [] };
 const runId = session.start('breakfast-cereal')!;
 const run = () => session.getSnapshot().runs.find(item => item.id === runId)!;
 const confirmedFoods = () => run().candidates.flatMap(candidate => candidate.status === 'confirmed' && candidate.food ? [candidate.food] : []);
 const compare = (selectedProfile = profile, panels: ConfirmedPanel[] = []) => rankShelfFoods({ foods: confirmedFoods(), categoryId: run().categoryId, profile: selectedProfile, panels, now });
 session.pause(runId);
 assert.equal(session.reviewObservation(runId, observation('Testbrand Orchard Original Cereal'), catalog), true);
 assert.equal(run().candidates[0].status, 'needs_confirmation');
 assert.equal(compare().ranked.length, 0, 'even a complete catalog name cannot join the ranking before confirmation');
 assert.equal(session.confirm(runId, run().candidates[0].id, shelfFoodKey(lowFat)), true);
 assert.equal(session.reviewObservation(runId, observation('Testbrand Meadow Reduced Sugar Cereal'), catalog), true);
 const second = run().candidates.find(candidate => candidate.status === 'needs_confirmation')!;
 assert.equal(session.confirm(runId, second.id, shelfFoodKey(lowSodium)), true);
 assert.equal(session.reviewObservation(runId, observation('Testbrand Orchard Original Cereal'), catalog), true);
 assert.equal(run().candidates.length, 2, 'a repeated OCR view does not create another ranking entry');
 const beforeRank = JSON.stringify(session.getSnapshot());
 assert.deepEqual(compare().ranked.map(item => [item.food.id, item.tier]), [[lowFat.id, 1], [lowSodium.id, 2]]);
 const hypertension: Profile = { ...profile, revision: 2, primary: 'hypertension', conditions: ['hypertension'] };
 const changed = compare(hypertension);
 assert.deepEqual(changed.ranked.map(item => [item.food.id, item.tier]), [[lowSodium.id, 1], [lowFat.id, 2]]);
 assert.equal(changed.profileRevision, 2);
 assert.ok(changed.ranked.every(item => item.food.id !== unseen.id), 'unseen catalog alternatives never fill the shelf ranking');
 const older: ConfirmedPanel = { id: 'old-context', testDate: '2026-09-01', importedAt: '2026-10-14T11:00:00Z', confirmed: true, measurements: [{ analyte: 'hdl', rawValue: '50', unit: 'mg/dL', comparator: '=' }] };
 const latest: ConfirmedPanel = { id: 'latest-context', testDate: '2026-10-01', importedAt: '2026-10-02T00:00:00Z', confirmed: true, measurements: [{ analyte: 'ldl', rawValue: '120', unit: 'mg/dL', comparator: '=' }] };
 // This separate flow supplies confirmed core facts directly; real import is covered by realReportShelfFlow.
 const withLipidContext = compare(hypertension, [latest, older]);
 assert.equal(withLipidContext.panelId, latest.id);
 assert.deepEqual(withLipidContext.ranked.map(item => item.tier), [1, 1]);
 const restricted = compare({ ...hypertension, revision: 3, restrictions: ['halal'] });
 assert.equal(restricted.ranked.length, 0); assert.equal(restricted.excluded.length, 2);
 assert.equal(JSON.stringify(session.getSnapshot()), beforeRank, 'profile and lipid comparisons do not rewrite observations or session facts');
 session.finish(runId);
 const nextRun = session.start('cookies'); assert.ok(nextRun);
 assert.equal(run().candidates.length, 2); assert.equal(run().state, 'finished');
 assert.equal('profile' in run(), false); assert.equal('panels' in run(), false);
 assert.equal(new ShelfSession().getSnapshot().runs.length, 0, 'a new process archive has no restored shelf state');
});
