import { test } from 'node:test';
import assert from 'node:assert/strict';
import { demoPanel, newSnapshot, type BetaRepository, type BetaSnapshot, type PanelRecord } from '../src/beta.ts';
import { LocalSession } from '../src/session.ts';
import { RealReportCoordinator } from '../src/realReport.ts';
import { REAL_REPORT_CONSENT_VERSION, type LipidEvidence } from '../src/realReportEvidence.ts';
import { registerPanelImport } from '../src/reportImports.ts';
import { correctPanel } from '../src/reports.ts';
import { ShelfSession } from '../src/shelfSession.ts';
import { rankShelfFoods } from '../src/shelfRanking.ts';
import type { Profile } from '../src/types.ts';
import { food, observation } from './shelfTestHelpers.ts';

test('source-linked real import and confirmation personalize shelf ranks locally across corrections and reopening', async () => {
 const now = '2026-10-14T12:00:00.000Z';
 const profile: Profile = { revision: 1, age: 40, pregnancy: 'not-pregnant', primary: 'hypertension', conditions: ['hypertension'], intent: 'both', restrictions: [] };
 const sample = { ...demoPanel('sample', now), confirmed: true, status: 'ready' as const, testDate: '2026-10-14', measurements: [{ analyte: 'triglycerides' as const, rawValue: '900', unit: 'mg/dL' as const, comparator: '=' as const }] };
 let disk: BetaSnapshot = { ...newSnapshot(), profile, betaConsent: { version: REAL_REPORT_CONSENT_VERSION, acceptedAt: now }, panels: [sample] };
 const repository: BetaRepository = { read: async () => structuredClone(disk), write: async next => { disk = structuredClone(next); }, clear: async () => {} };
 const local = new LocalSession(repository); await local.initialize();
 let calls = 0;
 const extract = async (input: LipidEvidence) => { calls++; return structuredClone(input); };
 const worker = new RealReportCoordinator(local, extract, { now: () => new Date(now) });
 const lowFat = food(1, { name: 'Testbrand Orchard Original Cereal', nutrients: { caloriesKcal: 350, saturatedFatG: 1, sodiumMg: 500, fiberG: 6, sugarsG: 4 } });
 const lowSodium = food(2, { name: 'Testbrand Meadow Original Cereal', nutrients: { caloriesKcal: 250, saturatedFatG: 5, sodiumMg: 100, fiberG: 6, sugarsG: 2 } });
 const shelf = new ShelfSession({ now: () => new Date(now), processNonce: 'report-ranking-test' });
 const runId = shelf.start('breakfast-cereal')!; shelf.pause(runId);
 assert.equal(shelf.reviewObservation(runId, observation('', 1, 'first'), [lowFat, lowSodium]), true);
 assert.equal(shelf.reviewObservation(runId, observation('', 2, 'second'), [lowFat, lowSodium]), true);
 const foods = shelf.getSnapshot().runs[0].candidates.flatMap(item => item.status === 'confirmed' && item.food ? [item.food] : []);
 assert.equal(foods.length, 2);
 const rank = (session = local, selectedProfile = profile) => rankShelfFoods({ foods, categoryId: 'breakfast-cereal', profile: selectedProfile, panels: session.snapshot.panels, panelChoice: session.snapshot.panelChoice, now: Date.parse(now) });
 assert.deepEqual(rank().ranked.map(item => [item.food.id, item.tier]), [[lowSodium.id, 1], [lowFat.id, 2]]);
 assert.equal(rank().panelId, null, 'a later-dated sample cannot become real-food health context');
 const latestSource = 'sha256:' + 'a'.repeat(64), olderSource = 'sha256:' + 'b'.repeat(64);
 const latestId = '00000000-0000-4000-8000-000000000001', olderId = '00000000-0000-4000-8000-000000000002';
 const latest: LipidEvidence = { schemaVersion: 1, testDate: '2026-10-01', measurements: [{ analyte: 'ldl', rawValue: '128', unit: 'mg/dL', comparator: '=', sourcePage: 1 }], issues: [] };
 const older: LipidEvidence = { schemaVersion: 1, testDate: '2026-09-20', measurements: [{ analyte: 'hdl', rawValue: '50', unit: 'mg/dL', comparator: '=', sourcePage: 1 }], issues: [] };
 const confirm = async (id: string, fingerprint: string, importedAt: string) => {
  const checked = worker.result(fingerprint)!;
  const candidate: Extract<PanelRecord, { synthetic: false }> = { id, kind: 'report', fingerprint, importedAt, testDate: checked.testDate!, synthetic: false, confirmed: true, status: 'ready', analysis: null, measurements: checked.measurements };
  assert.equal(await local.commit(data => registerPanelImport(data, candidate).snapshot), true);
 };
 assert.equal(await worker.run(latestSource, latest), 'saved');
 assert.equal(rank().panelId, null, 'a completed model check alone does not confirm a report');
 await confirm(latestId, latestSource, '2026-10-02T00:00:00.000Z');
 assert.equal(await worker.run(olderSource, older), 'saved');
 await confirm(olderId, olderSource, now);
 assert.equal(calls, 2);
 const personalized = rank();
 assert.equal(personalized.panelId, latestId, 'printed test date wins over later import and sample dates');
 assert.equal(personalized.panelTestDate, latest.testDate);
 assert.deepEqual(personalized.ranked.map(item => item.tier), [1, 1], 'LDL adds saturated-fat tradeoffs to the sodium comparison');
 assert.ok(personalized.priorities.some(item => item.origins.includes('Confirmed LDL context')));
 const profileChanged = rank(local, { ...profile, revision: 2, primary: 'cardiovascular', conditions: ['cardiovascular'] });
 assert.deepEqual(profileChanged.ranked.map(item => [item.food.id, item.tier]), [[lowFat.id, 1], [lowSodium.id, 2]]);
 assert.equal(calls, 2, 'profile changes only rerank locally');
 const immutableJournal = JSON.stringify(local.snapshot.reportImports);
 const original = local.snapshot.panels.find(item => item.id === latestId)!;
 assert.equal(await local.commit(data => correctPanel(data, original, { testDate: latest.testDate, measurements: [...latest.measurements, { analyte: 'triglycerides', rawValue: '600', unit: 'mg/dL', comparator: '=', sourcePage: 2 }] }, now)), true);
 const held = rank(); assert.equal(held.status, 'needs-information'); assert.equal(held.ranked.length, 0);
 assert.ok(held.excluded.every(item => item.reasons.some(reason => reason.includes('individualized nutrition plan'))));
 assert.equal(JSON.stringify(local.snapshot.reportImports), immutableJournal, 'source corrections cannot rewrite what the provider received');
 assert.equal(await worker.run(latestSource), 'reused'); assert.equal(calls, 2);
 const reopened = new LocalSession(repository); await reopened.initialize();
 const reopenedWorker = new RealReportCoordinator(reopened, extract);
 assert.equal(await reopenedWorker.run(latestSource), 'reused');
 assert.equal(rank(reopened).panelId, latestId); assert.equal(rank(reopened).ranked.length, 0);
 assert.equal(calls, 2, 'reopening, correction and repeated ranking never analyze a completed report again');
 assert.equal('scans' in disk && disk.scans.length, 0, 'shelf observations are not persisted alongside reports');
});
